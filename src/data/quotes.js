const getDayOfYear = () => {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  return Math.floor((now - start) / 86400000);
};

export const getTodayQuote = () => QUOTES[getDayOfYear() % QUOTES.length];
